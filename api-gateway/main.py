# --------------------------------------------------
# HELPER: FORWARD REQUEST TO A MICROSERVICE
# --------------------------------------------------

async def forward_request(
    request: Request,
    service_url: str,
    path: str,
):
    # Forward request headers, including the Authorization header.
    headers = dict(request.headers)

    # Remove headers that should be generated by the HTTP client.
    headers.pop("host", None)
    headers.pop("content-length", None)
    headers.pop("connection", None)

    body = await request.body()

    try:
        async with httpx.AsyncClient(timeout=30.0) as client:
            upstream_response = await client.request(
                method=request.method,
                url=f"{service_url}/{path.lstrip('/')}",
                params=request.query_params,
                content=body if body else None,
                headers=headers,
            )

        response_headers = {
            key: value
            for key, value in upstream_response.headers.items()
            if key.lower() not in {
                "content-length",
                "transfer-encoding",
                "connection",
                "content-encoding",
            }
        }

        return Response(
            content=upstream_response.content,
            status_code=upstream_response.status_code,
            headers=response_headers,
        )

    except httpx.RequestError:
        raise HTTPException(
            status_code=502,
            detail=f"Could not connect to service at {service_url}",
        )


